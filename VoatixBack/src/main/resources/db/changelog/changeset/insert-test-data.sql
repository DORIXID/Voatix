    DECLARE
        idea_rec       RECORD;
        user_id_val    INT;
        comment_id_val BIGINT;
        vote_count     INT;
        i              INT;
        -- Массив фраз для комментариев
        comment_texts  TEXT[] := ARRAY [
            'Отличная мысль, давно этого ждал!',
            'Не уверен, что это окупится, но звучит круто.',
            'CoffeeWay станет намного лучше с этой фичей.',
            'А это не слишком дорого выйдет?',
