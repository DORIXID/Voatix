            'Видел такое в Старбаксе, там это работает на ура.',
            'Наконец-то дельное предложение!',
            'Мне кажется, бариста не справятся с такой нагрузкой.',
            'Поддерживаю! Особенно пункт про качество зерна.'
            ];
    BEGIN
        -- Проходим по каждой идее проекта CoffeeWay (ID 1-50)
        FOR idea_rec IN SELECT id, date_time FROM public.ideas WHERE project_id = 1
            LOOP

                -- 1. ГЕНЕРИРУЕМ ЛАЙКИ И ДИЗЛАЙКИ (votingestimates)
                vote_count := floor(random() * 16 + 5); -- От 5 до 20 голосов
                FOR user_id_val IN (SELECT id FROM public.users ORDER BY random() LIMIT vote_count)
                    LOOP
                        -- Используем ON CONFLICT, чтобы не упасть при дубликатах
                        INSERT INTO public.votingestimates (idea_id, user_id, is_like)
                        VALUES (idea_rec.id, user_id_val, random() > 0.3) -- 70% вероятность лайка
                        ON CONFLICT DO NOTHING;
                    END LOOP;

                -- 2. ГЕНЕРИРУЕМ ПО 10 КОММЕНТАРИЕВ К КАЖДОЙ ИДЕЕ
                FOR i IN 1..10
                    LOOP
                        -- Выбираем случайного пользователя для комментария
                        user_id_val := (SELECT id FROM public.users ORDER BY random() LIMIT 1);

                        INSERT INTO public.comments (idea_id, user_id, text, date_time)
                        VALUES (idea_rec.id,
                                user_id_val,
                                comment_texts[floor(random() * 10 + 1)],
                                idea_rec.date_time +
                                (interval '1 hour' * floor(random() * 48 + 1)) -- Через 1-48 часов после идеи
                               )
                        RETURNING id INTO comment_id_val;

                        -- 3. ГЕНЕРИРУЕМ ОЦЕНКИ К КОММЕНТАРИЯМ (commentraitings)
                        -- Пусть у каждого комментария будет 2-5 оценок
                        FOR user_id_val IN (SELECT id FROM public.users ORDER BY random() LIMIT floor(random() * 4 + 2))
                            LOOP
                                INSERT INTO public.commentraitings (comment_id, user_id, is_like)
                                VALUES (comment_id_val, user_id_val, random() > 0.2)
                                ON CONFLICT DO NOTHING;
                            END LOOP;
                    END LOOP;

            END LOOP;
    END
$$;
